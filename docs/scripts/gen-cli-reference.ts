import { writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const docsRoot = join(import.meta.dirname, '..')
const outPath = join(docsRoot, 'content', '(public)', 'commands', 'reference.mdx')
const runner = (
  process.env.JACKIN_HELP_CMD ?? 'mise exec -- mbx +1.99.1 run -p jackin --'
).split(' ')

type Help = { path: string[]; text: string; children: string[] }

async function help(path: string[]): Promise<Help> {
  const proc = Bun.spawn([...runner, ...path, '--help'], {
    stdout: 'pipe',
    stderr: 'ignore',
    stdin: 'ignore',
  })
  const text = (await new Response(proc.stdout).text()).trimEnd()
  const code = await proc.exited
  if (code !== 0 || text === '') {
    throw new Error(`jackin ${path.join(' ')} --help exited with ${code}`)
  }
  return { path, text, children: subcommands(text) }
}

function subcommands(text: string): string[] {
  const lines = text.split('\n')
  const start = lines.findIndex((line) => line === 'Commands:')
  if (start === -1) return []
  const names: string[] = []
  for (const line of lines.slice(start + 1)) {
    if (line.trim() === '') break
    const name = line.match(/^ {2}(\S+)\s/)?.[1]
    if (name && name !== 'help') names.push(name)
  }
  return names
}

async function walk(path: string[], out: Help[]): Promise<void> {
  const node = await help(path)
  out.push(node)
  for (const child of node.children) {
    await walk([...path, child], out)
  }
}

function render(nodes: Help[]): string {
  const parts = [
    '---',
    'title: Command reference',
    'description: The help text of every jackin command, generated from the jackin binary.',
    '---',
    '',
    '{/* GENERATED by docs/scripts/gen-cli-reference.ts from `jackin --help`. Run `bun run gen:cli` in docs/ to regenerate. */}',
    '',
    'This page holds the output of `jackin <command> --help` for every command. `--gateway` is a global option and every command accepts it.',
    '',
  ]
  for (const node of nodes) {
    const name = ['jackin', ...node.path].join(' ')
    const level = node.path.length <= 1 ? '##' : '###'
    parts.push(`${level} ${name}`, '', '```text', node.text, '```', '')
  }
  return parts.join('\n')
}

const nodes: Help[] = []
await walk([], nodes)
await writeFile(outPath, render(nodes), 'utf8')
console.log(`gen-cli-reference: wrote ${nodes.length} commands to ${outPath}`)
